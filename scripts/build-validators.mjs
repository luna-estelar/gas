// Generates the protocol's precompiled timeline validator with AJV standalone.
// The browser bundles ship under a Content Security Policy without
// 'unsafe-eval', so no validator may be compiled at runtime: AJV builds its
// validators with `new Function`, which the browser blocks. Compiling the fixed
// protocol schemas here instead keeps the structural gate and leaves AJV's
// compiler out of every bundle.
//
// Run with `pnpm build:validators` after changing `packages/protocol/schemas/1.0`
// or upgrading ajv. `pnpm check:validators` (used by `pnpm test`) fails when the
// committed output no longer matches the schemas.
import assert from 'node:assert/strict';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standaloneCode from 'ajv/dist/standalone/index.js';
import addFormats from 'ajv-formats';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const protocolRoot = path.join(root, 'packages', 'protocol');
const schemaRoot = path.join(protocolRoot, 'schemas', '1.0');
const fixtureRoot = path.join(protocolRoot, 'test', 'fixtures');

export const OUTPUT_FILE = path.join(protocolRoot, 'generated', 'timeline-validator.mjs');

const SCHEMA_BASE = 'https://gas.luna-estelar.com/protocol/1.0';
const TIMELINE_ID = `${SCHEMA_BASE}/timeline.schema.json`;

// The timeline validator and every schema it references. The remaining protocol
// schemas are contracts for consumers and CI fixtures; nothing validates against
// them at runtime, so precompiling them would ship dead code.
const SCHEMAS = ['common', 'resources', 'timeline'];

// AJV emits this one CommonJS require even with `code.esm`, so the generated
// module rewrites it into an import. Keeping the match exact means an AJV
// upgrade that changes the shape fails loudly rather than silently emitting
// `require` into an ES module.
const UCS2LENGTH_REQUIRE = /require\("ajv\/dist\/runtime\/ucs2length"\)\.default/g;

const BANNER = `// Generated by scripts/build-validators.mjs. Do not edit.
// Regenerate with \`pnpm build:validators\` after changing the protocol schemas
// or upgrading ajv; \`pnpm check:validators\` fails when this file is stale.
import ucs2lengthModule from 'ajv/dist/runtime/ucs2length.js';

// Node hands an imported CommonJS module its \`module.exports\`; bundler interop
// may unwrap the default binding already.
const ucs2length = ucs2lengthModule.default ?? ucs2lengthModule;
`;

async function loadSchemas() {
  const schemas = [];
  for (const name of SCHEMAS) {
    schemas.push(JSON.parse(await readFile(path.join(schemaRoot, `${name}.schema.json`), 'utf8')));
  }
  return schemas;
}

/** The repo-canonical AJV setup, with code generation enabled for standalone output. */
function createAjv(schemas, { standalone = false } = {}) {
  const options = { allErrors: true, strict: false };
  const ajv = new Ajv2020(standalone ? { ...options, code: { source: true, esm: true } } : options);
  addFormats(ajv);
  for (const schema of schemas) ajv.addSchema(schema);
  return ajv;
}

export function rewriteRuntimeImports(code) {
  const matches = code.match(UCS2LENGTH_REQUIRE) ?? [];
  assert.equal(
    matches.length,
    1,
    `Expected exactly one ucs2length require in the generated validator, found ${matches.length}. ` +
      'An ajv upgrade may have changed its standalone output.'
  );
  const rewritten = code.replace(UCS2LENGTH_REQUIRE, 'ucs2length');
  assert.doesNotMatch(
    rewritten,
    /\brequire\(/,
    'The generated validator still contains a CommonJS require.'
  );
  assert.doesNotMatch(
    rewritten,
    /new Function|\beval\(/,
    'The generated validator still generates code at runtime.'
  );
  return `${BANNER}${rewritten}\n`;
}

export async function generate() {
  const schemas = await loadSchemas();
  const ajv = createAjv(schemas, { standalone: true });
  return rewriteRuntimeImports(standaloneCode(ajv, { validateTimeline: TIMELINE_ID }));
}

async function timelineFixtures() {
  const names = ['timeline-finite', 'timeline-infinite', 'timeline-level', 'timeline-loop'];
  const fixtures = [];
  for (const name of names) {
    fixtures.push({
      name,
      value: JSON.parse(await readFile(path.join(fixtureRoot, `${name}.json`), 'utf8'))
    });
  }
  return fixtures;
}

// Mutations of a valid fixture that the schemas must reject. These cover the
// keywords the timeline leans on: bounds, additionalProperties, the playback
// oneOf, referenced $defs, and the one format in the schema set.
function negativeCases(valid) {
  return [
    { name: 'negative arrangedBars', value: { ...valid, arrangedBars: -1 } },
    { name: 'unknown member', value: { ...valid, unexpectedMember: true } },
    { name: 'playback missing declaredBars', value: { ...valid, playback: { mode: 'finite' } } },
    { name: 'unknown playback mode', value: { ...valid, playback: { mode: 'sideways' } } },
    { name: 'empty timelineId', value: { ...valid, timelineId: '' } },
    { name: 'missing formatVersion', value: { ...valid, formatVersion: undefined } },
    {
      name: 'resource uri that is not a uri-reference',
      value: {
        ...valid,
        resources: [{ resourceId: 'r1', kind: 'audio', uri: 'has space', mediaType: 'audio/wav' }]
      }
    }
  ];
}

/**
 * Imports generated code that has not been written to disk yet. The generated
 * module imports ajv's runtime helper by package specifier, which a data URL
 * cannot resolve, so the specifier is rewritten to an absolute file URL first.
 */
async function importGenerated(code) {
  const require = createRequire(import.meta.url);
  const resolved = pathToFileURL(require.resolve('ajv/dist/runtime/ucs2length')).href;
  const loadable = code.replace(/'ajv\/dist\/runtime\/ucs2length\.js'/, JSON.stringify(resolved));
  const url = `data:text/javascript;base64,${Buffer.from(loadable).toString('base64')}`;
  return import(url);
}

/** Asserts the generated validator agrees with a freshly compiled one. */
export async function selfTest(code) {
  const { validateTimeline } = await importGenerated(code);
  const compiled = createAjv(await loadSchemas()).getSchema(TIMELINE_ID);
  assert(compiled, 'The timeline schema should be registered.');

  const fixtures = await timelineFixtures();
  for (const fixture of fixtures) {
    assert.equal(compiled(fixture.value), true, `${fixture.name} should compile-validate`);
    assert.equal(
      validateTimeline(fixture.value),
      true,
      `${fixture.name} should pass the generated validator`
    );
  }

  const cases = negativeCases(fixtures[0].value);
  for (const invalid of cases) {
    assert.equal(
      compiled(invalid.value),
      false,
      `${invalid.name} should be rejected when compiled`
    );
    assert.equal(
      validateTimeline(invalid.value),
      false,
      `${invalid.name} should be rejected by the generated validator`
    );
    assert.deepEqual(
      (validateTimeline.errors ?? []).map((error) => error.schemaPath),
      (compiled.errors ?? []).map((error) => error.schemaPath),
      `${invalid.name} should report the same problems as the compiled validator`
    );
  }

  return { fixtures: fixtures.length, negatives: cases.length };
}

async function readCommitted() {
  try {
    return await readFile(OUTPUT_FILE, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return undefined;
    throw error;
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const args = process.argv.slice(2);
  if (args.length > 1 || (args.length === 1 && args[0] !== '--check')) {
    console.error('usage: node scripts/build-validators.mjs [--check]');
    process.exit(2);
  }
  const check = args[0] === '--check';
  const code = await generate();
  const counts = await selfTest(code);
  const committed = await readCommitted();

  if (check) {
    if (committed !== code) {
      console.error(
        `${path.relative(root, OUTPUT_FILE)} is out of date. Run \`pnpm build:validators\`.`
      );
      process.exit(1);
    }
    console.log(
      `Precompiled validator is current: ${counts.fixtures} fixtures accepted and ${counts.negatives} invalid cases rejected.`
    );
  } else {
    if (committed !== code) {
      await mkdir(path.dirname(OUTPUT_FILE), { recursive: true });
      await writeFile(OUTPUT_FILE, code);
    }
    console.log(
      `Wrote ${path.relative(root, OUTPUT_FILE)}: ${counts.fixtures} fixtures accepted and ${counts.negatives} invalid cases rejected.`
    );
  }
}
